from __future__ import annotations

from collections.abc import Sequence
from datetime import date, datetime
from typing import Any, Protocol, Self

from banana_english.domain.interfaces.recommendation import ItemHistory
from banana_english.domain.models import (
    Account,
    Attempt,
    AuthSession,
    Conversation,
    ConversationScenario,
    Exercise,
    Job,
    LearnerProfile,
    ListeningLesson,
    ListeningQuestion,
    MasteryEvent,
    Role,
    Skill,
    SkillMastery,
    SpeakingPrompt,
    User,
    UserSummary,
    VocabularyCard,
    VocabularyItem,
)


class ContentRepository(Protocol):
    """Read-only, versioned learning content (loaded from content/)."""

    def list_skills(self) -> list[Skill]: ...
    def get_skill(self, skill_id: str) -> Skill | None: ...
    def get_exercise(self, exercise_id: str) -> Exercise | None: ...
    def list_exercises(self, skill_id: str) -> list[Exercise]: ...
    def get_vocabulary_item(self, item_id: str) -> VocabularyItem | None: ...
    def list_vocabulary(self, skill_id: str) -> list[VocabularyItem]: ...
    def list_listening(self) -> list[ListeningLesson]: ...
    def get_listening(self, lesson_id: str) -> ListeningLesson | None: ...
    def get_listening_question(
        self, question_id: str
    ) -> tuple[ListeningLesson, ListeningQuestion] | None: ...
    def list_speaking(self) -> list[SpeakingPrompt]: ...
    def get_speaking(self, prompt_id: str) -> SpeakingPrompt | None: ...
    def list_scenarios(self) -> list[ConversationScenario]: ...
    def get_scenario(self, scenario_id: str) -> ConversationScenario | None: ...


class LearnerRepository(Protocol):
    def add(self, user: User, profile: LearnerProfile) -> None: ...
    def get(self, user_id: str) -> tuple[User, LearnerProfile] | None: ...


class AuthRepository(Protocol):
    def add_account(self, account: Account) -> None: ...
    def account_by_email(self, email: str) -> Account | None: ...
    def add_session(self, session: AuthSession) -> None: ...
    def get_session(self, token_hash: str) -> AuthSession | None: ...
    def delete_session(self, token_hash: str) -> None: ...
    def session_user(self, token_hash: str) -> tuple[AuthSession, User] | None: ...


class UserDirectory(Protocol):
    """Users for administration and teacher scope (roles come from here, never a request)."""

    def get(self, user_id: str) -> User | None: ...
    def email(self, user_id: str) -> str | None: ...
    def search(
        self,
        query: str = "",
        role: Role | None = None,
        active: bool | None = None,
        limit: int = 50,
        offset: int = 0,
        only_ids: Sequence[str] | None = None,
    ) -> tuple[list[UserSummary], int]: ...
    def summary(self, user_id: str) -> UserSummary | None: ...
    def set_role(self, user_id: str, role: Role) -> None: ...
    def set_active(self, user_id: str, active: bool) -> None: ...
    def revoke_sessions(self, user_id: str) -> int: ...
    def count_active(self, role: Role) -> int: ...
    def counts(self) -> dict[str, dict[str, int]]: ...
    def created_since(self, since: datetime) -> int: ...
    def link(self, teacher_id: str, student_id: str, at: datetime) -> bool: ...
    def unlink(self, teacher_id: str, student_id: str) -> bool: ...
    def is_linked(self, teacher_id: str, student_id: str) -> bool: ...
    def student_ids(self, teacher_id: str) -> list[str]: ...
    def teacher_ids(self, student_id: str) -> list[str]: ...
    def unlink_all(self, user_id: str) -> None: ...


class MasteryRepository(Protocol):
    def get(self, learner_id: str, skill_id: str) -> SkillMastery | None: ...
    def list(self, learner_id: str) -> list[SkillMastery]: ...
    def save(self, mastery: SkillMastery) -> None: ...
    def add_event(self, event: MasteryEvent) -> None: ...
    def events(
        self, learner_id: str, since: datetime, skill_id: str | None = None
    ) -> list[MasteryEvent]: ...
    def active_days(self, learner_id: str, since: datetime) -> dict[date, int]: ...


class AttemptRepository(Protocol):
    def add(self, attempt: Attempt) -> None: ...
    def get(self, attempt_id: str) -> Attempt | None: ...
    def count(self, learner_id: str) -> tuple[int, int]: ...
    def item_history(self, learner_id: str) -> dict[str, ItemHistory]: ...
    def recent_mistake_counts(
        self, learner_id: str, limit: int = 50
    ) -> dict[str, dict[str, int]]: ...
    def recent(self, learner_id: str, limit: int = 20) -> list[Attempt]: ...


class CardRepository(Protocol):
    def get(self, learner_id: str, item_id: str) -> VocabularyCard | None: ...
    def save(self, card: VocabularyCard) -> None: ...
    def list_due(self, learner_id: str, today: date, limit: int) -> list[VocabularyCard]: ...
    def seen_item_ids(self, learner_id: str) -> frozenset[str]: ...
    def created_since(self, learner_id: str, since: datetime) -> int: ...


class ConversationRepository(Protocol):
    def add(self, conversation: Conversation) -> None: ...
    def get(self, conversation_id: str) -> Conversation | None: ...
    def save(self, conversation: Conversation) -> None: ...


class JobRepository(Protocol):
    def add(self, job: Job) -> None: ...
    def get(self, job_id: str) -> Job | None: ...
    def save(self, job: Job) -> None: ...


class LLMCallLog(Protocol):
    def record(self, entry: dict[str, Any]) -> None: ...


class UnitOfWork(Protocol):
    """One transaction."""

    learners: LearnerRepository
    auth: AuthRepository
    mastery: MasteryRepository
    attempts: AttemptRepository
    cards: CardRepository
    conversations: ConversationRepository
    jobs: JobRepository
    users: UserDirectory

    def __enter__(self) -> Self: ...
    def __exit__(self, *exc: object) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
