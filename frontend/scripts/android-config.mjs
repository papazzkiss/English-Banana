// Write mobile/config.js: the server URL the Android app opens first.
//   BANANA_APP_URL=https://example.com node scripts/android-config.mjs
// Without BANANA_APP_URL, the current Cloudflare quick-tunnel URL is read from
// `docker compose logs tunnel` (the public link of this deployment). The app lets the learner
// change the URL later, so a stale one only means one extra step on the phone.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

function tunnelUrl() {
  try {
    const logs = execSync("docker compose logs tunnel", {
      cwd: join(here, "..", ".."),
      stdio: ["ignore", "pipe", "ignore"],
    }).toString();
    const found = logs.match(/https:\/\/[a-z0-9-]+\.trycloudflare\.com/g);
    return found ? found[found.length - 1] : "";
  } catch {
    return "";
  }
}

let url = (process.env.BANANA_APP_URL ?? "").trim();
let source = "BANANA_APP_URL";
if (!url) {
  url = tunnelUrl();
  source = "docker compose logs tunnel";
}
if (url) {
  const parsed = new URL(url);
  if (parsed.protocol !== "https:") throw new Error(`BANANA_APP_URL must be https:// (got ${url})`);
  url = parsed.origin;
}

writeFileSync(
  join(here, "..", "mobile", "config.js"),
  `// Generated by scripts/android-config.mjs (${source}). Do not edit.\n` +
    `window.BANANA_APP_URL = ${JSON.stringify(url)};\n`,
);
console.log(url ? `Android app URL: ${url} (from ${source})` : "Android app URL: none (the app will ask)");
